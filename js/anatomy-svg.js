// Closed path symmetric about x=100: `start` and the last segment end lie on the centre line.
function anatomySymPath(start, segs) {
  const m = x => +(200 - x).toFixed(2);
  let d = `M${start[0]},${start[1]}` + segs.map(s => ` C${s[0]},${s[1]} ${s[2]},${s[3]} ${s[4]},${s[5]}`).join('');
  for(let i = segs.length - 1; i >= 0; i--) {
    const s = segs[i], prev = i ? segs[i - 1].slice(4, 6) : start;
    d += ` C${m(s[2])},${s[3]} ${m(s[0])},${s[1]} ${m(prev[0])},${prev[1]}`;
  }
  return d + ' Z';
}

// One six-pack block: outer edge at xo, linea alba edge at xi.
function anatomyAbBlock(xo, xi, y0, y1) {
  return `M${xi},${y0} C${xi - 3},${y0 - 1} ${xo + 2},${y0 - 0.5} ${xo},${y0 + 2} C${xo - 1},${y0 + 5} ${xo - 1},${y1 - 5} ${xo + 0.5},${y1 - 1.5} ` +
    `C${xo + 3},${y1 + 0.5} ${xi - 3},${y1 + 1} ${xi},${y1} C${xi + 0.5},${y1 - 4} ${xi + 0.5},${y0 + 4} ${xi},${y0} Z`;
}

