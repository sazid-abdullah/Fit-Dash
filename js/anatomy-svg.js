function anatomyViewSvg(view, primary, secondary, offsetX) {
  const names = { ...(typeof MUSCLE_NAMES !== 'undefined' ? MUSCLE_NAMES : {}), ...ANATOMY_EXTRA_NAMES };
  const state = id => primary.includes(id) ? 'primary' : secondary.includes(id) ? 'secondary' : '';
  const muscle = ([id, d, fibres = []]) => {
    const st = state(id);
    return `<path class="fg-muscle${st ? ` fg-${st}` : ''}" data-muscle="${id}" d="${d}"><title>${names[id] || id}</title></path>` +
      fibres.map(f => `<path class="fg-fiber${st ? ' fg-fiber-on' : ''}" d="${f}"/>`).join('');
  };
  const side = (view === 'front' ? ANATOMY_FRONT : ANATOMY_BACK).map(muscle).join('') +
    (view === 'front' ? ANATOMY_FRONT_DETAIL : ANATOMY_BACK_DETAIL).map(d => `<path class="fg-detail" d="${d}"/>`).join('');
  let centre;
  if(view === 'front') {
    centre = '<path class="fg-detail" d="M100,172 C98.8,172 98.4,173.6 100,174.6 C101.6,173.6 101.2,172 100,172 Z"/>';
  } else {
    const traps = ['traps', anatomySymPath([100, 44], [[96,46, 93,50, 92,56], [88,64, 78,70, 66,75], [74,79, 84,84, 88,92], [92,104, 96,120, 100,136]]),
      ['M95,52 C91,62 82,70 70,75', 'M98,84 C93,88 90,92 88,96', 'M99,112 C97,104 93,98 90,94', 'M105,52 C109,62 118,70 130,75', 'M102,84 C107,88 110,92 112,96', 'M101,112 C103,104 107,98 110,94']];
    centre = muscle(traps) + '<path class="fg-detail" d="M100,138 C100,160 100,180 100,198"/>';
  }
  return `<g transform="translate(${offsetX},0)">
    <path class="fg-body" d="${ANATOMY_SILHOUETTE}"/>
    <g>${side}</g><g transform="matrix(-1 0 0 1 200 0)">${side}</g>${centre}
    <text x="100" y="410" text-anchor="middle" class="fg-view-label">${view === 'front' ? 'ANTERIOR' : 'POSTERIOR'}</text></g>`;
}

